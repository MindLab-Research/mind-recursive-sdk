#!/usr/bin/env python
"""GRPO: sample a group, score it, normalise within the group, update.

Run it with no arguments; change the ``CONFIG`` block below to change the run::

    uv run python recipes/03_grpo.py

Data format, one prompt per line, plus whatever the reward function needs::

    {"messages": [{"role": "user", "content": "What is 2+2?"}], "answer": "4"}

## The loop

For each prompt:

1. **sample** ``group_size`` completions from the *current* policy
2. **score** each one (``reward_fn`` below -- replace it with yours)
3. **normalise** rewards within the group: ``(r - mean) / std``. That is the
   "group relative" in GRPO, and it is why no value network is needed: the
   group's own mean is the baseline.
4. **update** with the normalised advantage as a per-token weight

## Why sampling happens on a separate object

Training and sampling are different planes with different upstreams
(training vs inference backends), and GRPO needs **token-aligned logprobs**, so the
sampler is created separately from the trainer -- both off the same
``ServiceClient``.

## The part that needs care

A group whose rewards are all equal has zero variance, so every advantage is
zero and the step is pure noise. Those groups are skipped rather than
contributing a no-op update; the count is reported so you can see when a reward
function has stopped discriminating.
"""

from __future__ import annotations

import re
import statistics
import sys
from dataclasses import dataclass
from pathlib import Path

import numpy as np

import mind_recursive as mr
# Recipes are standalone scripts, runnable from any directory, so the shared
# helper module sits next to them rather than on the import path.
sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common import DEMO_GRPO, Timer, fmt, load_jsonl_records

# Rendering is recipe-local: it is not the SDK's job. See _renderer.py.
from _renderer import get_renderer


@dataclass
class Config:
    """Everything this run needs. Edit ``CONFIG`` below, then run the file."""

    #: JSONL of prompts plus whatever ``reward_fn`` needs, or ``None`` for the
    #: built-in arithmetic set.
    data: str | None = None
    model: str = "Qwen/Qwen3.8-27B"
    #: Relay origin. ``None`` reads ``MIND_RECURSIVE_BASE_URL`` from the environment.
    base_url: str | None = None
    iterations: int = 5
    #: Samples per prompt -- GRPO's G. Must be at least 2: the group's own mean
    #: is the baseline, so a group of one has nothing to normalise against.
    group_size: int = 8
    learning_rate: float = 2e-5
    lora_rank: int = 32
    #: Must be > 0, or every sample in a group is identical and carries no signal.
    temperature: float = 1.0
    top_p: float = 0.95
    max_new_tokens: int = 256
    max_length: int = 4096


CONFIG = Config()


# --------------------------------------------------------------------- reward
def reward_fn(completion: str, record: dict) -> float:
    """Score one completion. **This is the part you replace.**

    The demo task is arithmetic with a known answer, so the reward is exact
    match on the final number, with a small bonus for being terse. Shape it
    however your task needs; only the relative ordering within a group matters,
    because rewards are normalised per group.
    """
    expected = str(record.get("answer", "")).strip()
    numbers = re.findall(r"-?\d+(?:\.\d+)?", completion)
    if not numbers:
        return 0.0
    correct = numbers[-1] == expected
    if not correct:
        return 0.0
    brevity = max(0.0, 1.0 - len(completion) / 200.0)
    return 1.0 + 0.2 * brevity


# ------------------------------------------------------------------ advantages
def group_advantages(rewards: list[float]) -> list[float] | None:
    """Normalise rewards within a group; ``None`` when the group is degenerate.

    ``(r - mean) / std`` is GRPO's baseline-free advantage. If every sample
    scored the same, std is 0: there is no signal, and dividing would either
    blow up or silently produce zeros. Returning ``None`` lets the caller skip
    the group and count it.
    """
    if len(rewards) < 2:
        return None
    mean = statistics.fmean(rewards)
    std = statistics.pstdev(rewards)
    if std < 1e-8:
        return None
    return [(r - mean) / std for r in rewards]


# ------------------------------------------------------------------ datum build
def build_datum(
    prompt_tokens: list[int],
    completion_tokens: list[int],
    logprobs: list[float],
    advantage: float,
) -> mr.Datum:
    """One policy-gradient example.

    Three tensors, all aligned to the full token sequence:

    * ``weights``     -- the advantage on completion positions, 0 on the prompt.
      The prompt was not generated by the policy, so it carries no gradient.
    * ``target_tokens`` -- next-token targets, shifted left.
    * ``logprobs``    -- the sampler's logprob for each completion token, i.e.
      the behaviour policy. ``importance_sampling`` needs it to form the ratio
      against the current policy.
    """
    tokens = prompt_tokens + completion_tokens
    prompt_len = len(prompt_tokens)

    # Shifted by one: position i predicts token i+1.
    targets = np.asarray([*tokens[1:], 0], dtype=np.int64)

    weights = np.zeros(len(tokens), dtype=np.float32)
    behaviour = np.zeros(len(tokens), dtype=np.float32)
    for offset, logprob in enumerate(logprobs[: len(completion_tokens)]):
        position = prompt_len + offset - 1  # the position that predicts this token
        if 0 <= position < len(tokens):
            weights[position] = advantage
            behaviour[position] = logprob

    return mr.Datum(
        model_input=mr.ModelInput.from_ints(tokens),
        loss_fn_inputs={
            "weights": mr.TensorData(weights, "float32"),
            "target_tokens": mr.TensorData(targets, "int64"),
            "logprobs": mr.TensorData(behaviour, "float32"),
        },
    )


# ------------------------------------------------------------------------ loop
def train(args: Config, records: list[dict]) -> str:
    renderer = get_renderer(args.model, max_length=args.max_length)

    sc = mr.ServiceClient(base_url=args.base_url)
    with sc:
        trainer = sc.create_lora_trainer(
            base_model=args.model, rank=args.lora_rank, train_unembed=False
        )
        sc.log(f"session {sc.session_id}, trainer {trainer.model_id} created", step=0)

        sampling_params = mr.SamplingParams(
            max_tokens=args.max_new_tokens,
            temperature=args.temperature,  # needs to be >0: identical samples carry no signal
            top_p=args.top_p
        )
        weights_path = ""

        # 运行日志是给人读的时间线；控制台「运行日志」tab 只渲染 type="log"。
        # rollout 的数值走 sc.metric，日志只记「这一轮发生了什么」。
        sc.log(
            f"GRPO started: {len(records)} prompts x {args.group_size} samples, "
            f"{args.iterations} iterations, model {args.model}",
            step=0
        )

        try:
            for iteration in range(args.iterations):
                # The sampler reads a checkpoint, so the policy must be published
                # before each round -- otherwise the group is drawn from a stale
                # policy and the importance ratio is wrong.
                with Timer() as publish:
                    weights_path = trainer.save_weights_only(
                        f"iter-{iteration + 1}"
                    ).result()
                sampler = trainer.create_sampler(model_path=weights_path)
                sc.log(
                    f"iter {iteration + 1}/{args.iterations}: published "
                    f"{weights_path}, sampling {len(records)} prompts x "
                    f"{args.group_size}",
                    step=iteration + 1,
                )

                batch: list[mr.Datum] = []
                all_rewards: list[float] = []
                skipped = 0
                first_text = ""

                with Timer() as rollout:
                    for index, record in enumerate(records, start=1):
                        prompt_tokens = renderer.prompt_tokens(record["messages"])
                        response = sampler.sample(
                            prompt_tokens,
                            num_samples=args.group_size,
                            sampling_params=sampling_params,
                        ).result()

                        rewards, usable = [], []
                        for sequence in response.sequences:
                            text = renderer.decode(sequence.tokens)
                            first_text = first_text or text
                            rewards.append(reward_fn(text, record))
                            usable.append(sequence)

                        advantages = group_advantages(rewards)
                        all_rewards.extend(rewards)
                        if advantages is None:
                            skipped += 1
                            sc.log(
                                f"iter {iteration + 1} prompt {index}/{len(records)}: "
                                "rewards all equal, group skipped",
                                level="warning",
                                step=iteration + 1,
                            )
                            continue

                        sc.log(
                            f"iter {iteration + 1} prompt {index}/{len(records)}: "
                            f"rewards {min(rewards):.2f}..{max(rewards):.2f}, "
                            f"mean {statistics.fmean(rewards):.2f}, "
                            f"{len(usable)} samples",
                            step=iteration + 1,
                        )

                        for sequence, advantage in zip(usable, advantages):
                            if not sequence.logprobs:
                                # No logprobs means no behaviour policy, so the
                                # importance ratio cannot be formed.
                                continue
                            batch.append(
                                build_datum(
                                    prompt_tokens,
                                    sequence.tokens,
                                    sequence.logprobs,
                                    advantage,
                                )
                            )

                if iteration == 0 and first_text.strip():
                    # 第一轮留一条真实 completion：日志里能直接看到模型在答什么，
                    # 而不是只有 loss 和 reward 两个数字。
                    sc.log(
                        f"iter 1 sample: {first_text.strip()[:500]}",
                        step=iteration + 1,
                    )

                if not batch:
                    message = (
                        f"iteration {iteration + 1}: every group was degenerate "
                        f"({skipped} skipped) -- the reward function is not "
                        "discriminating between samples"
                    )
                    print(f"  {message}")
                    sc.log(message, level="warning", step=iteration + 1)
                    continue

                with Timer() as update:
                    out = trainer.forward_backward(
                        batch, loss_fn="importance_sampling"
                    ).result()
                    trainer.optim_step(
                        mr.AdamParams(learning_rate=args.learning_rate)
                    ).result()

                mean_reward = statistics.fmean(all_rewards) if all_rewards else 0.0
                sc.metric(
                    {
                        "loss/train": out.loss,
                        "reward/mean": mean_reward,
                        "reward/max": max(all_rewards) if all_rewards else 0.0,
                        "batch/examples": len(batch),
                        "batch/degenerate_groups": skipped,
                    },
                    step=iteration + 1,
                    stage="training",
                    total=args.iterations,
                    timings={
                        "publish_weights": publish.seconds,
                        "rollout": rollout.seconds,
                        "update": update.seconds,
                    },
                )
                print(
                    f"iter {iteration + 1}/{args.iterations}  "
                    f"loss {fmt(out.loss)}  mean_reward {mean_reward:.3f}  "
                    f"examples {len(batch)}  skipped {skipped}"
                )
                sc.log(
                    f"iter {iteration + 1}/{args.iterations}: loss {fmt(out.loss)}, "
                    f"mean_reward {mean_reward:.3f}, {len(batch)} examples, "
                    f"{skipped} degenerate groups",
                    step=iteration + 1,
                )

            final = trainer.save_weights_only("grpo-final").result()
            sc.log(f"GRPO done, saved sampler weights to {final}", step=args.iterations)
            sc.summary(iterations=args.iterations)
            print(f"\nsampler weights: {final}")
            return final

        except Exception as exc:
            # 日志给人看；event 给平台看，带稳定的 type/code 供它处理失败。
            sc.log(f"run failed: {type(exc).__name__}: {exc}", level="error")
            sc.event(
                "run.failed",
                level="error",
                code=type(exc).__name__,
                message=str(exc),
            )
            raise


def main() -> int:
    config = CONFIG

    # Validated here rather than trusted: both of these produce a run that
    # looks like it works and learns nothing.
    if config.group_size < 2:
        print(
            "CONFIG.group_size must be at least 2: GRPO normalises within a group",
            file=sys.stderr
        )
        return 2
    if config.temperature <= 0:
        print(
            "CONFIG.temperature must be > 0, or every sample is identical",
            file=sys.stderr
        )
        return 2

    records = load_jsonl_records(config.data) if config.data else DEMO_GRPO

    try:
        train(config, records)
    except mr.ConfigurationError as exc:
        print(f"configuration problem: {exc}", file=sys.stderr)
        return 2
    except mr.RequestFailedError as exc:
        print(f"the server rejected the work: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
